//! Workspace tasks, run as `cargo xtask <task>`.
//!
//! `generate` runs progenitor over the OpenAPI documents in `spec/` and
//! writes the resulting clients to `pangram-rs/src/generated/`. The output
//! is committed, so a change to a spec shows up as a reviewable diff in the
//! generated code.
//!
//! The file upload API (`spec/pangram-file-upload.json`) is a
//! `multipart/form-data` endpoint, which progenitor cannot generate, so that
//! client is written by hand in `pangram-rs/src/upload.rs`.
//!
//! Error responses (`4XX`/`5XX`) are removed from the documents before
//! generation. Pangram does not document its error bodies, and progenitor's
//! typed error path drops the HTTP status when a body fails to decode (for
//! example a plain-text 429). Without declared error responses every non-2xx
//! reply surfaces as `Error::UnexpectedResponse(reqwest::Response)`, which
//! `Pangram::finish` turns into a fully populated `Error::Api`.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{bail, Context, Result};
use clap::Parser;
use progenitor::{GenerationSettings, Generator, InterfaceStyle};

#[derive(Parser)]
#[command(name = "xtask", about = "workspace tasks")]
enum Xtask {
    /// Regenerate the clients in pangram-rs/src/generated from spec/.
    Generate,
}

/// Module name and spec path (relative to the workspace root) for each
/// generated client.
const SPECS: &[(&str, &str)] = &[
    ("text", "spec/pangram-text.json"),
    ("plagiarism", "spec/pangram-plagiarism.json"),
];

const GENERATED_DIR: &str = "pangram-rs/src/generated";

fn main() -> Result<()> {
    match Xtask::parse() {
        Xtask::Generate => generate(),
    }
}

fn generate() -> Result<()> {
    let root = workspace_root();
    let out_dir = root.join(GENERATED_DIR);
    fs::create_dir_all(&out_dir).with_context(|| format!("creating {}", out_dir.display()))?;

    for (module, spec_path) in SPECS {
        let out_file = out_dir.join(format!("{module}.rs"));
        println!(
            "generating {} from {spec_path}",
            out_file.strip_prefix(&root).unwrap().display()
        );

        let file =
            fs::File::open(root.join(spec_path)).with_context(|| format!("opening {spec_path}"))?;
        let mut spec: openapiv3::OpenAPI =
            serde_json::from_reader(file).with_context(|| format!("parsing {spec_path}"))?;
        strip_error_responses(&mut spec);

        let mut settings = GenerationSettings::default();
        settings
            .with_interface(InterfaceStyle::Positional)
            .with_derive("PartialEq");
        let mut generator = Generator::new(&settings);
        let tokens = generator
            .generate_tokens(&spec)
            .with_context(|| format!("generating client for {spec_path}"))?;
        let ast = syn::parse2(tokens).context("generated code does not parse")?;
        let contents = format!(
            "// The contents of this file are generated by `cargo xtask generate`\n\
             // from {spec_path}; do not edit.\n\n{}",
            line_doc_comments(&prettyplease::unparse(&ast))
        );
        fs::write(&out_file, contents)
            .with_context(|| format!("writing {}", out_file.display()))?;
    }

    // Normalize with rustfmt so the checked-in files pass `cargo fmt --check`.
    println!("formatting pangram-rs");
    let status = Command::new("cargo")
        .args(["fmt", "-p", "pangram-rs"])
        .current_dir(&root)
        .status()
        .context("running cargo fmt")?;
    if !status.success() {
        bail!("cargo fmt failed");
    }
    Ok(())
}

/// Removes every non-success response so progenitor leaves error handling to
/// the caller (see the module docs).
fn strip_error_responses(spec: &mut openapiv3::OpenAPI) {
    use openapiv3::{ReferenceOr, StatusCode};
    for (_, item) in spec.paths.paths.iter_mut() {
        let ReferenceOr::Item(item) = item else {
            continue;
        };
        let ops = [
            &mut item.get,
            &mut item.put,
            &mut item.post,
            &mut item.delete,
            &mut item.options,
            &mut item.head,
            &mut item.patch,
            &mut item.trace,
        ];
        for op in ops.into_iter().flatten() {
            op.responses.default = None;
            op.responses.responses.retain(|code, _| match code {
                StatusCode::Code(c) => (200..300).contains(c),
                StatusCode::Range(r) => *r == 2,
            });
        }
    }
}

/// Rewrites block doc comments as `///` lines.
///
/// prettyplease renders a multi-line `#[doc]` attribute as a `/** ... */`
/// block whose continuation lines are indented to the item's depth. Markdown
/// treats indented lines as code blocks, so rustdoc renders the text as code
/// and compiles it as a doctest, which fails.
fn line_doc_comments(code: &str) -> String {
    let mut out = String::with_capacity(code.len());
    // Indentation of the block comment currently being rewritten.
    let mut open: Option<String> = None;
    for line in code.lines() {
        match &open {
            None => {
                let trimmed = line.trim_start();
                let indent = &line[..line.len() - trimmed.len()];
                match trimmed.strip_prefix("/**") {
                    Some(rest) => match rest.strip_suffix("*/") {
                        Some(text) => push_doc(&mut out, indent, text),
                        None => {
                            push_doc(&mut out, indent, rest);
                            open = Some(indent.to_string());
                        }
                    },
                    None => {
                        out.push_str(line);
                        out.push('\n');
                    }
                }
            }
            Some(indent) => {
                let text = line
                    .strip_prefix(indent.as_str())
                    .unwrap_or(line.trim_start());
                match text.strip_suffix("*/") {
                    Some(last) => {
                        if !last.trim().is_empty() {
                            push_doc(&mut out, indent, last);
                        }
                        open = None;
                    }
                    None => push_doc(&mut out, indent, text),
                }
            }
        }
    }
    out
}

fn push_doc(out: &mut String, indent: &str, text: &str) {
    out.push_str(indent);
    out.push_str("///");
    let text = text.trim_end();
    if !text.is_empty() {
        out.push(' ');
        out.push_str(text);
    }
    out.push('\n');
}

fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask lives one level below the workspace root")
        .to_path_buf()
}

#[cfg(test)]
mod tests {
    use super::*;
    use clap::CommandFactory;

    #[test]
    fn cli_is_well_formed() {
        Xtask::command().debug_assert();
    }

    #[test]
    fn block_doc_comments_become_lines() {
        let input = "impl Client {\n    /**Title\n\n    Body line.\n\n    */\n    pub fn f() {}\n    /**one line*/\n    pub fn g() {}\n}\n";
        let expected = "impl Client {\n    /// Title\n    ///\n    /// Body line.\n    ///\n    pub fn f() {}\n    /// one line\n    pub fn g() {}\n}\n";
        assert_eq!(line_doc_comments(input), expected);
    }

    #[test]
    fn other_lines_are_untouched() {
        let input = "/// already\nlet s = \"/* not doc */\";\n";
        assert_eq!(line_doc_comments(input), input);
    }
}
